import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { createServer } from 'node:http';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { git } from '../git.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SOURCE_CONTROL_PLAYWRIGHT || 'playwright');
const plugin = fileURLToPath(new URL('../', import.meta.url));
const scratch = fileURLToPath(new URL('../../.test-work/ui-tests/', import.meta.url));
mkdirSync(scratch, { recursive: true });

test('real MCP App UI: changes, branches, fetch/pull/push, graph, diffs and conflict recovery', { timeout: 240000 }, async () => {
  const root = mkdtempSync(path.join(scratch, 'repo-'));
  const second = mkdtempSync(path.join(scratch, 'other-'));
  for (const repo of [root, second]) {
    git(repo, 'init', '-b', 'main'); git(repo, 'config', 'user.name', 'UI Test'); git(repo, 'config', 'user.email', 'test@example.invalid');
    git(repo, 'config', 'core.autocrlf', 'false');
    writeFileSync(path.join(repo, 'tracked.txt'), 'base\n');
    git(repo, 'add', '.'); git(repo, 'commit', '-m', 'initial');
  }
  const write = (file, content) => writeFileSync(path.join(root, file), content);
  write('tracked.txt', 'staged\n'); git(root, 'add', '.'); write('tracked.txt', 'unstaged\n');
  write("--[日本語] 'file'.txt", 'new\n');
  const config = path.join(scratch, 'repositories.json');
  writeFileSync(config, JSON.stringify([{ id: 'test', label: 'UI Test', path: root }, { id: 'second', label: 'Other repo', path: second }]));
  const client = new Client({ name: 'browser-test-host', version: '1.0.0' });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(plugin, 'server.mjs'), '--config', config] }));
  const hostSource = `import { AppBridge, PostMessageTransport } from '@modelcontextprotocol/ext-apps/app-bridge';
    const frame = document.querySelector('iframe');
    window.bridge = new AppBridge(null, { name:'Test Host', version:'1.0.0' }, { serverTools:{} }, { hostContext:{theme:'light'} });
    bridge.oncalltool = params => window.callMcp(params);
    bridge.oninitialized = async () => { await bridge.sendToolInput({arguments:{}}); await bridge.sendToolResult(await window.callMcp({name:'git.open',arguments:{}})); };
    await bridge.connect(new PostMessageTransport(frame.contentWindow, frame.contentWindow));
    frame.src = '/panel';`;
  const bundle = await build({ absWorkingDir: plugin, stdin: { contents: hostSource, resolveDir: plugin }, bundle: true, write: false, format: 'esm' });
  const http = createServer((req, res) => {
    res.setHeader('Content-Type', req.url === '/host.js' ? 'application/javascript' : 'text/html; charset=utf-8');
    res.end(req.url === '/panel' ? readFileSync(path.join(plugin, 'dist/panel.html')) : req.url === '/host.js' ? bundle.outputFiles[0].text : '<!doctype html><html><body style="margin:0"><iframe title="Source Control" style="border:0;width:100%;height:900px"></iframe><script type="module" src="/host.js"></script></body></html>');
  });
  await new Promise(resolve => http.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.SOURCE_CONTROL_CHROMIUM ? { executablePath: process.env.SOURCE_CONTROL_CHROMIUM } : {}) });
    const page = await browser.newPage({ viewport: { width: 380, height: 900 } });
    const errors = []; const calls = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.exposeFunction('callMcp', params => { calls.push(params.name); return client.callTool(params); });
    await page.goto(`http://127.0.0.1:${http.address().port}`);
    const frame = page.frameLocator('iframe');
    const waitReady = async () => { await frame.locator('#panel[aria-busy="false"]').waitFor(); };
    await waitReady();
    assert.equal(await frame.locator('#branch').textContent(), 'main');
    assert.equal(await frame.locator('#staged-count').textContent(), '1');
    assert.equal(await frame.locator('#unstaged-count').textContent(), '2');
    assert.equal(calls.filter(name => name === 'git.open').length, 1);
    assert.equal(await frame.locator('#commit').isDisabled(), true);
    assert.equal(await frame.locator('#fetch').isDisabled(), true);
    await frame.getByRole('button', { name: 'ステージ済み差分: tracked.txt', exact: true }).click(); await waitReady();
    assert.match(await frame.locator('#diff-content').textContent(), /\+staged/);
    assert.doesNotMatch(await frame.locator('#diff-content').textContent(), /unstaged/);
    await frame.locator('#close-diff').click();
    assert.equal(await frame.locator('body').evaluate(el => el.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(plugin, 'preview-light.png'), fullPage: true });
    await page.evaluate(() => bridge.setHostContext({ theme: 'dark' }));
    await frame.locator('html[data-theme="dark"]').waitFor();
    await page.screenshot({ path: path.join(plugin, 'preview-dark.png'), fullPage: true });

    await frame.locator('#message').fill('draft for first repo');
    await frame.locator('#repository').selectOption('second'); await waitReady();
    assert.equal(await frame.locator('#message').inputValue(), '');
    await frame.locator('#message').fill('other draft');
    await frame.locator('#repository').selectOption('test'); await waitReady();
    assert.equal(await frame.locator('#message').inputValue(), 'draft for first repo');

    const discard = frame.getByRole('button', { name: '変更を破棄: tracked.txt', exact: true });
    await discard.click();
    assert.equal(await frame.locator('#discard-dialog').evaluate(el => el.open), true);
    assert.equal(calls.includes('git.discard'), false);
    await frame.locator('#cancel-discard').click();
    assert.equal(readFileSync(path.join(root, 'tracked.txt'), 'utf8'), 'unstaged\n');
    await discard.click(); await frame.locator('#confirm-discard').click(); await waitReady();
    assert.equal(readFileSync(path.join(root, 'tracked.txt'), 'utf8'), 'staged\n');
    assert.equal(await frame.locator('#staged-count').textContent(), '1');

    const unusual = "--[日本語] 'file'.txt";
    await frame.getByRole('button', { name: `ステージ: ${unusual}`, exact: true }).click(); await waitReady();
    assert.equal(await frame.locator('#staged-count').textContent(), '2');
    await frame.getByRole('button', { name: `アンステージ: ${unusual}`, exact: true }).click(); await waitReady();
    write(unusual, 'changed externally');
    await frame.getByRole('button', { name: `変更を破棄: ${unusual}`, exact: true }).click();
    await frame.locator('#confirm-discard').click(); await waitReady();
    assert.match(await frame.locator('#notice').textContent(), /再読み込み/);
    assert.ok(existsSync(path.join(root, unusual)));
    await frame.locator('#refresh').click(); await waitReady();
    await frame.getByRole('button', { name: `変更を破棄: ${unusual}`, exact: true }).click();
    await frame.locator('#confirm-discard').click(); await waitReady();
    assert.equal(existsSync(path.join(root, unusual)), false);

    git(root, 'config', 'user.name', ''); git(root, 'config', 'user.email', '');
    await frame.locator('#message').fill('UI commit');
    await frame.locator('#commit').click(); await waitReady();
    assert.equal(await frame.locator('#message').inputValue(), 'UI commit');
    assert.equal(await frame.locator('#staged-count').textContent(), '1');
    assert.equal(await frame.locator('#notice').getAttribute('role'), 'alert');
    git(root, 'config', 'user.name', 'UI Test'); git(root, 'config', 'user.email', 'test@example.invalid');
    await frame.locator('#message').press('Control+Enter'); await waitReady();
    assert.equal(git(root, 'log', '-1', '--format=%s').trim(), 'UI commit');
    assert.equal(await frame.locator('#message').inputValue(), '');
    assert.equal(await frame.locator('#commit').isDisabled(), true);
    assert.equal(await frame.locator('#total').textContent(), '変更なし');

    // A private, local bare repository exercises the actual network command paths without contacting user remotes.
    const origin = path.join(scratch, 'ui-remote-' + path.basename(root) + '.git');
    const peer = path.join(scratch, 'ui-peer-' + path.basename(root));
    git(scratch, 'init', '--bare', '-b', 'main', origin);
    git(root, 'remote', 'add', 'origin', origin); git(root, 'push', '-u', 'origin', 'main');
    git(scratch, 'clone', origin, peer);
    git(peer, 'config', 'user.name', 'UI Peer'); git(peer, 'config', 'user.email', 'test@example.invalid'); git(peer, 'config', 'core.autocrlf', 'false');
    function commitAt(repo, file, content, message) {
      writeFileSync(path.join(repo, file), content); git(repo, 'add', '--', file); git(repo, 'commit', '-m', message);
    }
    commitAt(peer, 'tracked.txt', 'from remote\n', 'Remote update'); git(peer, 'push', 'origin', 'main');
    await frame.locator('#refresh').click(); await waitReady();
    assert.equal(await frame.locator('#remote-selector').inputValue(), 'origin');
    await frame.locator('#fetch').click(); await waitReady();
    assert.match(await frame.locator('#tracking').textContent(), /↓1/);
    assert.equal(readFileSync(path.join(root, 'tracked.txt'), 'utf8'), 'staged\n');
    await frame.locator('#pull').click(); await waitReady();
    assert.equal(readFileSync(path.join(root, 'tracked.txt'), 'utf8'), 'from remote\n');
    assert.match(await frame.locator('#tracking').textContent(), /↓0/);

    await frame.locator('#new-branch').click();
    await frame.locator('#branch-name').fill('feature/ui-created');
    await frame.locator('#create-branch').click(); await waitReady();
    assert.equal(await frame.locator('#branch').textContent(), 'feature/ui-created');
    commitAt(root, 'publish.txt', 'published\n', 'UI published branch');
    await frame.locator('#refresh').click(); await waitReady();
    await frame.locator('#push').click();
    assert.match(await frame.locator('#discard-file').textContent(), /origin\/feature\/ui-created/);
    assert.equal(calls.includes('git.push'), false);
    await frame.locator('#confirm-discard').click(); await waitReady();
    assert.equal(git(origin, 'rev-parse', 'refs/heads/feature/ui-created').trim(), git(root, 'rev-parse', 'HEAD').trim());
    await frame.locator('#branch-selector').selectOption('refs/heads/main'); await waitReady();
    assert.equal(await frame.locator('#branch').textContent(), 'main');

    git(peer, 'switch', '-c', 'feature/remote-only');
    commitAt(peer, 'remote-only.txt', 'remote branch\n', 'Remote-only branch'); git(peer, 'push', 'origin', 'HEAD');
    await frame.locator('#fetch').click(); await waitReady();
    await frame.locator('#branch-selector').selectOption('refs/remotes/origin/feature/remote-only'); await waitReady();
    assert.equal(await frame.locator('#branch').textContent(), 'feature/remote-only');
    assert.match(await frame.locator('#tracking').textContent(), /origin\/feature\/remote-only/);

    git(root, 'switch', '-c', 'graph-side');
    commitAt(root, 'graph-side.txt', 'side change\n', '<img src=x onerror=alert(1)>');
    git(root, 'switch', 'feature/remote-only');
    commitAt(root, 'graph-main.txt', 'main change\n', 'Graph main change');
    git(root, 'merge', '--no-ff', '--no-edit', 'graph-side');
    await frame.locator('#refresh').click(); await waitReady();
    await frame.locator('#history-tab').click();
    assert.equal(await frame.locator('#history-view').isVisible(), true);
    assert.ok(await frame.locator('.graph-commit').count() >= 5);
    assert.equal(await frame.locator('#history img').count(), 0);
    assert.ok(await frame.locator('#history svg path[d*="L"]').count() > 0);
    assert.match(await frame.locator('#history').textContent(), /graph-side/);
    assert.equal(await frame.locator('#previous-history').isVisible(), false);
    assert.equal(await frame.locator('#more-history').isVisible(), false);
    assert.equal(await frame.locator('body').evaluate(el => el.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(plugin, 'preview-graph-dark.png'), fullPage: true });
    await page.evaluate(() => bridge.setHostContext({ theme: 'light' })); await frame.locator('html[data-theme="light"]').waitFor();
    await page.screenshot({ path: path.join(plugin, 'preview-graph-light.png'), fullPage: true });
    await frame.locator('.graph-commit').first().click(); await waitReady();
    assert.match(await frame.locator('#diff-content').textContent(), /\+side change/);
    assert.equal(await frame.locator('#diff-dialog img').count(), 0);
    await frame.locator('#close-diff').click();
    await page.evaluate(async () => bridge.sendToolResult(await callMcp({ name: 'git.status', arguments: { repo: 'test', limit: 2 } })));
    await frame.locator('#history-count').filter({ hasText: '1–2' }).waitFor();
    assert.equal(await frame.locator('#previous-history').isVisible(), false);
    assert.equal(await frame.locator('#more-history').isVisible(), true);
    await frame.locator('#more-history').click(); await waitReady();
    assert.match(await frame.locator('#history-count').textContent(), /3–4/);
    assert.equal(await frame.locator('#previous-history').isVisible(), true);
    await frame.locator('#previous-history').click(); await waitReady();
    assert.match(await frame.locator('#history-count').textContent(), /1–2/);
    await frame.locator('#history-tab').press('ArrowLeft');
    assert.equal(await frame.locator('#changes-view').isVisible(), true);

    const beforeConflict = git(root, 'rev-parse', 'HEAD').trim();
    commitAt(root, 'tracked.txt', 'local conflict\n', 'Local conflict');
    const conflictHead = git(root, 'rev-parse', 'HEAD').trim();
    commitAt(peer, 'tracked.txt', 'remote conflict\n', 'Remote conflict'); git(peer, 'push', 'origin', 'HEAD');
    await frame.locator('#refresh').click(); await waitReady();
    await frame.locator('#pull-strategy').selectOption('merge');
    await frame.locator('#pull').click(); await waitReady();
    assert.equal(await frame.locator('#operation-panel').isVisible(), true);
    assert.match(await frame.locator('#operation-title').textContent(), /merge/);
    assert.equal(await frame.getByRole('button', { name: 'ステージ: tracked.txt', exact: true }).isEnabled(), true);
    await frame.locator('#abort-operation').click(); await frame.locator('#confirm-discard').click(); await waitReady();
    assert.equal(git(root, 'rev-parse', 'HEAD').trim(), conflictHead);
    assert.equal(await frame.locator('#operation-panel').isVisible(), false);
    await frame.locator('#pull-strategy').selectOption('rebase');
    await frame.locator('#pull').click(); await waitReady();
    assert.match(await frame.locator('#operation-title').textContent(), /rebase/);
    write('tracked.txt', 'resolved via UI\n');
    await frame.locator('#refresh').click(); await waitReady();
    await frame.getByRole('button', { name: 'ステージ: tracked.txt', exact: true }).click(); await waitReady();
    await frame.locator('#continue-operation').click(); await waitReady();
    assert.equal(await frame.locator('#operation-panel').isVisible(), false);
    assert.equal(readFileSync(path.join(root, 'tracked.txt'), 'utf8'), 'resolved via UI\n');
    assert.notEqual(git(root, 'rev-parse', 'HEAD').trim(), beforeConflict);
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await client.close(); await new Promise(resolve => http.close(resolve)); }
});
